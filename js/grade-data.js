// ---------- 원본 문자열 → 객체 배열 변환 ----------
const GRADE_HANJA = [];
const _gradeSeen = new Set();

GRADE_LEVELS.forEach(function (lv) {
  const list = GRADE_RAW[lv.id] || [];
  list.forEach(function (row, idx) {
    const parts = String(row).split('|');
    if (parts.length < 3) return;
    const char = parts[0].trim();
    const meaning = parts[1].trim();
    const sound = parts[2].trim();
    if (!char || char.length !== 1) return;
    if (_gradeSeen.has(char)) return;
    _gradeSeen.add(char);

    GRADE_HANJA.push({
      id: 'gh_' + char,        // 급수가 바뀌어도 유지되는 고유 id
      char: char,
      meaning: meaning,        // 훈(뜻)
      sound: sound,            // 음(소리)
      grade: lv.id,            // 'g8' | 'g7II' | ... | 'adv'
      gradeOrder: lv.order,
      starter: STARTER_CHARS.indexOf(char) !== -1,
      index: idx + 1,
      hunmum: meaning + ' ' + sound
    });
  });
});

// ---------- 도우미 ----------
function getGradeChars(gradeId) {
  if (gradeId === 'all' || gradeId == null) return GRADE_HANJA.slice();
  return GRADE_HANJA.filter(function (h) { return h.grade === gradeId; });
}

function getGradeInfo(gradeId) {
  return GRADE_LEVELS.find(function (g) { return g.id === gradeId; }) || GRADE_LEVELS[0];
}

function getGradeCount(gradeId) {
  return getGradeChars(gradeId).length;
}

// 해당 급수까지의 누적 한자 (시험은 아래 급수 한자도 함께 출제됩니다)
function getCumulativeChars(gradeId) {
  const info = getGradeInfo(gradeId);
  return GRADE_HANJA.filter(function (h) { return h.gradeOrder <= info.order && h.grade !== 'adv'; });
}

// 예전 id(g9_一 등)를 새 id(gh_一)로 바꿔주는 마이그레이션 도우미
function migrateGradeId(oldId) {
  const m = /^g\d+_(.)$/.exec(oldId || '');
  return m ? 'gh_' + m[1] : oldId;
}

