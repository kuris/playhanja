// ---------- 변환 ----------
const GRADE_HANJA = [];
const _seen = new Set();

GRADE_LEVELS.forEach(function (lv) {
  (GRADE_RAW[lv.id] || []).forEach(function (row, idx) {
    const p = String(row).split('|');
    const char = p[0];
    if (!char || _seen.has(char)) return;
    _seen.add(char);
    GRADE_HANJA.push({
      id: 'gh_' + char,
      char: char,
      meaning: p[1],                 // 대표 훈
      sound: p[2],                   // 대표 음
      radical: p[3],                 // 부수
      strokes: Number(p[4]) || null,  // 총획 (어문회 기준)
      meaningFull: p[5] || p[1],     // 훈 전체 (예: 한국 나라)
      soundFull: p[6] || p[2],
      grade: lv.id,
      gradeOrder: lv.order,
      starter: STARTER_CHARS.indexOf(char) !== -1,
      index: idx + 1,
      hunmum: p[1] + ' ' + p[2]
    });
  });
});

// ---------- 도우미 ----------
function getGradeChars(gradeId) {
  if (gradeId === 'all' || gradeId == null) return GRADE_HANJA.slice();
  return GRADE_HANJA.filter(function (h) { return h.grade === gradeId; });
}
function getGradeInfo(gradeId) {
  return GRADE_LEVELS.find(function (g) { return g.id === gradeId; }) || GRADE_LEVELS[0];
}
function getGradeCount(gradeId) { return getGradeChars(gradeId).length; }

// 시험은 아래 급수 한자까지 함께 출제되므로 누적 범위를 돌려줍니다
function getCumulativeChars(gradeId) {
  const info = getGradeInfo(gradeId);
  return GRADE_HANJA.filter(function (h) { return h.gradeOrder <= info.order; });
}

// 한국어문회 기준 획수 (전통 자형). 없으면 null
const _strokeByChar = {};
GRADE_HANJA.forEach(function (h) { _strokeByChar[h.char] = h.strokes; });
function getOfficialStrokes(char) {
  return _strokeByChar[char] != null ? _strokeByChar[char] : null;
}
function getOfficialRadical(char) {
  const h = GRADE_HANJA.find(function (x) { return x.char === char; });
  return h ? h.radical : null;
}

// 예전 id(g9_一 등) → 새 id(gh_一)
function migrateGradeId(oldId) {
  const m = /^g\d+_(.)$/.exec(oldId || '');
  return m ? 'gh_' + m[1] : oldId;
}

