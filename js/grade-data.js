// ---------- 원본 문자열 → 객체 배열 변환 ----------
const GRADE_HANJA = [];
const _gradeSeen = new Set();

GRADE_LEVELS.forEach(function (lv) {
  const rows = GRADE_RAW[lv.id] || [];
  rows.forEach(function (row) {
    const parts = String(row).split('|');
    if (parts.length < 3) return;
    const char = parts[0].trim();
    const meaning = parts[1].trim();
    const sound = parts[2].trim();
    // 데이터 정리용 방어 코드 (중복 · 빈 값 제외)
    if (!char || char.length !== 1 || meaning === '-' || sound === '-') return;
    if (_gradeSeen.has(char)) return;
    _gradeSeen.add(char);

    GRADE_HANJA.push({
      id: 'g' + lv.id + '_' + char,
      char: char,
      meaning: meaning,   // 훈(뜻)
      sound: sound,       // 음(소리)
      grade: lv.id,
      hunmum: meaning + ' ' + sound  // "한 일" 형태의 훈음
    });
  });
});

// ---------- 도우미 함수 ----------
function getGradeChars(gradeId) {
  if (gradeId === 'all' || gradeId == null) return GRADE_HANJA.slice();
  return GRADE_HANJA.filter(function (h) { return h.grade === Number(gradeId); });
}

function getGradeInfo(gradeId) {
  return GRADE_LEVELS.find(function (g) { return g.id === Number(gradeId); }) || GRADE_LEVELS[0];
}

function getGradeCount(gradeId) {
  return getGradeChars(gradeId).length;
}

