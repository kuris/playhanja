const IDIOMS = IDIOM_RAW.map(function (row, idx) {
  const [idiom, reading, charStr, meaning, story, lesson, source, level, tag] = row;
  const hunmums = String(charStr).split('|');
  const chars = idiom.split('').map(function (ch, i) {
    const hm = (hunmums[i] || '').trim();
    const sp = hm.lastIndexOf(' ');
    return {
      char: ch,
      meaning: sp > 0 ? hm.slice(0, sp) : hm,   // 훈(뜻)
      sound: sp > 0 ? hm.slice(sp + 1) : (reading[i] || ''), // 음(소리)
      hunmum: hm,
      readingChar: reading[i] || ''
    };
  });

  return {
    id: 'idiom_' + (idx + 1),
    no: idx + 1,
    idiom: idiom,
    reading: reading,
    meaning: meaning,
    story: story,
    lesson: lesson,
    source: source,
    level: level,
    tag: tag,
    chars: chars
  };
});

function getIdiomsByLevel(level) {
  if (level === 'all' || level == null) return IDIOMS.slice();
  return IDIOMS.filter(function (i) { return i.level === Number(level); });
}

function getIdiomLevelInfo(level) {
  return IDIOM_LEVELS.find(function (l) { return l.id === Number(level); }) || IDIOM_LEVELS[0];
}

if (typeof window !== 'undefined') {
  window.IDIOM_LEVELS = IDIOM_LEVELS;
  window.IDIOMS = IDIOMS;
  window.getIdiomsByLevel = getIdiomsByLevel;
  window.getIdiomLevelInfo = getIdiomLevelInfo;
}
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { IDIOM_LEVELS, IDIOMS, getIdiomsByLevel, getIdiomLevelInfo };
}
