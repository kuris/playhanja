// 한 글자가 한자인지 판정 (CJK 통합 한자 영역)
function isHanjaChar(ch) {
  const c = ch.codePointAt(0);
  return (c >= 0x4E00 && c <= 0x9FFF) || (c >= 0x3400 && c <= 0x4DBF) || (c >= 0xF900 && c <= 0xFAFF);
}

const SUBWAY_STATIONS = [];

SUBWAY_LINES.forEach(function (line) {
  (SUBWAY_RAW[line.id] || []).forEach(function (row, idx) {
    const p = String(row).split('|');
    const ko = p[0];
    const mixed = p[1] || ko;
    const chars = Array.from(mixed);
    const hanjaChars = chars.filter(isHanjaChar);
    SUBWAY_STATIONS.push({
      id: 'sw_' + line.id + '_' + (idx + 1),
      line: line.id,
      order: idx + 1,
      ko: ko,               // 한글 역이름
      mixed: mixed,         // 혼용 표기 (서울驛 등)
      chars: chars,         // 표기를 한 글자씩 나눈 배열
      hanjaChars: hanjaChars,
      hanjaCount: hanjaChars.length,
      // 한자가 하나도 없으면 순우리말 역이름
      pureKorean: hanjaChars.length === 0,
      story: SUBWAY_STORY[ko] || null
    });
  });
});


