function getLineInfo(lineId) {
  return SUBWAY_LINES.find(function (l) { return l.id === lineId; }) || SUBWAY_LINES[0];
}

function getLineStations(lineId) {
  return SUBWAY_STATIONS.filter(function (s) { return s.line === lineId; });
}

// 여러 노선에 같은 이름이 있으면 환승역
const _linesByName = {};
SUBWAY_STATIONS.forEach(function (s) {
  (_linesByName[s.ko] = _linesByName[s.ko] || []).push(s.line);
});
function getTransferLines(ko, exceptLine) {
  return (_linesByName[ko] || []).filter(function (l) { return l !== exceptLine; });
}

// 한자 한 글자의 훈음을 찾습니다.
//  1) 급수 데이터에서 그대로 찾고
//  2) 없으면 이체자 표준형으로 다시 찾고 (표준자를 함께 알려줍니다)
//  3) 그래도 없으면 보충 훈음표에서 찾습니다.
// 어디에도 없으면 null 을 돌려줍니다.
function lookupHanja(ch) {
  if (typeof GRADE_HANJA !== 'undefined') {
    const direct = GRADE_HANJA.find(function (h) { return h.char === ch; });
    if (direct) return direct;

    const std = SUBWAY_VARIANT[ch];
    if (std) {
      const alt = GRADE_HANJA.find(function (h) { return h.char === std; });
      if (alt) {
        return Object.assign({}, alt, { char: ch, variantOf: std });
      }
    }
  }
  const ex = SUBWAY_EXTRA_HUN[ch];
  if (ex) {
    return { char: ch, meaning: ex.meaning, sound: ex.sound, grade: null, extra: true };
  }
  return null;
}

function getSubwayStats() {
  const total = SUBWAY_STATIONS.length;
  const pure = SUBWAY_STATIONS.filter(function (s) { return s.pureKorean; }).length;
  const storied = SUBWAY_STATIONS.filter(function (s) { return !!s.story; }).length;
  const charSet = new Set();
  SUBWAY_STATIONS.forEach(function (s) {
    s.hanjaChars.forEach(function (c) { charSet.add(c); });
  });
  return { total: total, pureKorean: pure, uniqueChars: charSet.size, storied: storied };
}

